#pragma once

// ============================================================================
// 装甲板的**值类型与纯几何**。
//
// 这个文件里没有状态、不碰图像、不认识配置，只吃 Bar 与标量 —— 因此主机侧
// 可以逐条单测（tests/host/armor_host_test.cpp 直接调 bar_ends / line_intersection
// / armor_center），不需要相机、RVV 或 SDK。
//
// 为什么灯条要有自己的类型与主轴，而不是直接用包围盒：
// **包围盒对旋转极其敏感**。一条 5x40 的灯条转 30°，包围盒变成 24x37 ——
// 长宽比 8.0→1.5、填充率 1.00→0.22，于是"长宽比门限"和"填充率门限"同时失效，
// 端点也会从"长轴端点"退化成"包围盒边中点"（偏出半个包围盒宽）。
// 而 len/thick/theta 取自二阶矩主轴（types.hpp::principal_axis），与旋转无关。
// ============================================================================

#include <cstdint>

namespace dart::detection::armor {

// 整数取绝对值。放在这里是因为几何（pair_span）、判据（pair_score）、
// 主控（assoc）三处都要用。
inline int32_t abs_i(int32_t v) { return v < 0 ? -v : v; }

// ---------------------------------------------------------------------------
// 灯条（画面绝对坐标；px = 像素数；border = 贴窗口边 → 长度只是下界）
// ---------------------------------------------------------------------------
struct Bar {
    int16_t  x = 0, y = 0, w = 0, h = 0;
    uint32_t px = 0;
    uint8_t  border = 0;
    float    len = 0.0f;   // 主轴长度（真实灯条长度）
    float    thick = 0.0f; // 次轴长度（真实厚度）
    float    theta = 0.0f; // 主轴方向（弧度，从 +x 轴起算，[-π/2, π/2]）

    int32_t bbox_len() const { return w > h ? w : h; } // 包围盒长边（只用于"远档"判断与打印）
    int32_t cx() const { return x + w / 2; }
    int32_t cy() const { return y + h / 2; }

    // 主轴与"竖直/水平"中较近者的夹角 —— **单位：度**，与 ArmorConfig 里的角度一致。
    // （踩过：这里先返回了弧度，于是 15° 的 0.26 被当成"0.26 度" < flat_deg=12，
    //   填充率门限又生效了，斜灯条照样被判死。角度一律用度，别混。）
    float axis_skew_deg() const {
        const float a = (theta < 0.0f ? -theta : theta) * 57.29577951308232f; // 0..90
        const float to_vert = 90.0f - a;
        return to_vert < a ? to_vert : a;
    }
};

// ---------------------------------------------------------------------------
// 灯条长轴的两个端点 = "上角点 / 下角点"。
//
// 正放（axis_skew <= flat_deg）时用包围盒边的中点 —— 与改造前**逐位一致**，
// 竖直/水平这个已经跑通的工况零回归。
// 斜的时候必须沿**主轴**取：包围盒上边中点根本不在灯条轴上（偏出半个包围盒宽），
// 四条"角点"就围不成那块四边形，板心会整体偏、而且逐帧抖。
// （轴方向 mod π 没有歧义：两个端点交换不影响两条对角线的交点。）
// ---------------------------------------------------------------------------
void bar_ends(const Bar &b, float flat_deg, int32_t *x0, int32_t *y0, int32_t *x1, int32_t *y1);

// ---------------------------------------------------------------------------
// 两条线段的交点：不平行、且交点同时落在两条线段之内才返回 true。
// 全整数：t/u 是有符号整数，只有最后求坐标做一次四舍五入除法 ——
// "交点在不在段内"因此是精确比较，不会因浮点误差把边界情形判反
// （角点几乎重合恰好是噪声最大的地方）。
// ---------------------------------------------------------------------------
bool line_intersection(int32_t x0, int32_t y0, int32_t x1, int32_t y1, int32_t x2, int32_t y2,
                       int32_t x3, int32_t y3, float min_sin, int32_t *ox, int32_t *oy);

// ---------------------------------------------------------------------------
// 板心 = A上—B下 与 A下—B上 两条连线的交点。
// **注意是交叉连线**：A 的长轴与 B 的长轴永远平行，拿它们求交没有交点（写错过）。
// ---------------------------------------------------------------------------
bool armor_center(const Bar &a, const Bar &b, float min_sin, float flat_deg, int32_t *cx,
                  int32_t *cy);

// ---------------------------------------------------------------------------
// 两条灯条中心在"垂直于长轴"方向上的距离 ∝ 灯尺（板上间距是固定的）
// ---------------------------------------------------------------------------
int32_t pair_span(const Bar &a, const Bar &b);

} // namespace dart::detection::armor
