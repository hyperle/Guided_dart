#pragma once

// ============================================================================
// 装甲板的**判据**：从"一块连通域"到"这是不是灯条 / 这两条像不像一块板"。
//
// 全部是纯函数（给配置、给值，出判定），不持有状态、不碰像素内存 ——
// 每个判据都是**必要条件**，任何一条不成立就否掉，这样"为什么没出结果"
// 在 Trace 里能一项一项对上（rejected / rejected_prior）。
//
// 与"认亲"（track 阶段）的分工：这里全是 detect 阶段的全门限判据；
// track 阶段一条形状判据都不做（只比位置与尺寸容差，见 armor_detector.cpp）。
// ============================================================================

#include <cstdint>

#include "detection/armor/armor_geometry.hpp"
#include "detection/measure/roi_measure.hpp"
#include "detection/config.hpp"
#include "detection/types.hpp"

namespace dart::detection::armor {

// ---------------------------------------------------------------------------
// 只填字段，不做任何判据。
// track 阶段的"认亲"用它：位置 + 尺寸容差就是全部判据。
//
// 主轴可用就用主轴（与旋转无关）；退化（1~2px 或病态矩）时退回包围盒口径。
// ---------------------------------------------------------------------------
void fill_bar(const RunLengthMeasurer::BlobInfo &b, Bar *out);

// ---------------------------------------------------------------------------
// detect 阶段的灯条判据（track 阶段**不进这里**）。
//
// 近档（包围盒长边 ≥ tiny_px）：长宽比 + 填充率可信，照用。
// 远档：几个像素的"长宽比"是量化噪声 → 改判与尺度无关的圆度（灯条不像圆）。
// ---------------------------------------------------------------------------
bool as_bar(const ArmorConfig &cfg, const RunLengthMeasurer::BlobInfo &b, int32_t s, Bar *out);

// ---------------------------------------------------------------------------
// 配对：两条灯条像不像同一块装甲板（全部是必要条件）
//   ① 同向 ② 两条一样粗 ③ 长度比 ④ 沿长轴投影重叠（并排，不是首尾相接）
//   ⑤ 中心距 <= gap_max_k·长边，且横向不重叠
// 分数 = 长度差百分比 + 沿长轴错位百分比 + 贴边罚分（被窗口削过的长度不可信）
// ---------------------------------------------------------------------------
bool pair_score(const ArmorConfig &cfg, const Bar &a, const Bar &b, int32_t *score);

// ---------------------------------------------------------------------------
// 板心与绿灯是不是同一个整体：径向距离 < near_k × 半径（平方比较，省开方）
// ---------------------------------------------------------------------------
bool same_body(const ArmorConfig &cfg, const TrackOutput &led, int32_t cx, int32_t cy);

// ---------------------------------------------------------------------------
// 刚性几何先验：板心相对绿灯的位置、两灯条间距必须是灯尺的固定倍数。
//
// 前提是"绿灯与装甲板固定在同一块板上"（已确认）。它**与距离无关**，
// 所以远档形状判据全不可信时，这是唯一还在工作的判据。
// ---------------------------------------------------------------------------
bool prior_ok(const ArmorConfig &cfg, const TrackOutput &led, int32_t s, const Bar &a, const Bar &b,
              int32_t cx, int32_t cy);

} // namespace dart::detection::armor
